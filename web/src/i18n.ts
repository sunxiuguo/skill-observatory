export const dictionaries: Record<Locale, Dict> = { "zh-CN": zh, en };
export const DEFAULT_LOCALE: Locale = "zh-CN";

// Walk a dotted path; missing keys fall back to English, then to the raw key.
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const resolve = (dict: unknown): string | undefined => {
    let cur: unknown = dict;
    for (const part of key.split(".")) {
      if (cur && typeof cur === "object" && part in (cur as Record<string, unknown>)) {
        cur = (cur as Record<string, unknown>)[part];
      } else return undefined;
    }
    return typeof cur === "string" ? cur : undefined;
  };
  let out = resolve(dictionaries[locale]) ?? resolve(en) ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}

export function reasonText(locale: Locale, code?: string): string {
  if (!code) return "";
  const key = code.toLowerCase();
  const mapped = translate(locale, `reason.${key}`);
  if (mapped !== `reason.${key}`) return mapped;
  // Unknown code: keep the stable machine code readable instead of hiding it.
  if (!/^[A-Z][A-Z0-9_]{0,95}$/.test(code)) return locale === "zh-CN" ? "证据待核对，原始原因见收据" : "Evidence needs verification; see the raw receipt";
  return locale === "zh-CN" ? `未登记的恢复原因（${code}）` : `Unregistered recovery reason (${code})`;
}

export function statusText(locale: Locale, code?: string): string {
  if (!code) return translate(locale, "common.unknown");
  const key=code.toLowerCase();
  const mapped = translate(locale, `status.${key}`);
  return mapped === `status.${key}` ? `${translate(locale,"common.unknown")} (${code})` : mapped;
}
